//! Embeds every built-in pack prompt: each `hub/packs/<pack>/prompts/*.md`
//! of every pack directory that has a `pack.json`. The list is generated,
//! so a new prompt file is served without touching the code (and a test in
//! `prompts.rs` checks the list against the directory).

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let packs = manifest.join("../../packs");
    let packs = packs.canonicalize().unwrap_or(packs);
    println!("cargo:rerun-if-changed={}", packs.display());

    let mut found: Vec<(String, String, PathBuf)> = Vec::new();
    let mut dirs: Vec<PathBuf> = fs::read_dir(&packs)
        .expect("hub/packs is readable")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.join("pack.json").is_file())
        .collect();
    dirs.sort();
    for dir in dirs {
        let pack = name_of(&dir);
        let prompts = dir.join("prompts");
        // Adding or removing a file changes the directory, which reruns this.
        println!("cargo:rerun-if-changed={}", dir.display());
        if !prompts.is_dir() {
            continue;
        }
        println!("cargo:rerun-if-changed={}", prompts.display());
        let mut files: Vec<PathBuf> = fs::read_dir(&prompts)
            .expect("prompts dir is readable")
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "md") && p.is_file())
            .collect();
        files.sort();
        for f in files {
            println!("cargo:rerun-if-changed={}", f.display());
            found.push((pack.clone(), name_of(&f), f));
        }
    }

    let mut out = String::from(
        "/// `(pack id, file name, contents)` of every built-in prompt, sorted by\n/// pack and file name. Generated by build.rs.\npub(crate) const SOURCES: &[(&str, &str, &str)] = &[\n",
    );
    for (pack, file, path) in &found {
        let _ = writeln!(
            out,
            "    ({pack:?}, {file:?}, include_str!({:?})),",
            path.display().to_string()
        );
    }
    out.push_str("];\n");
    let dest =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("prompt_sources.rs");
    fs::write(dest, out).expect("write prompt_sources.rs");
}

fn name_of(p: &Path) -> String {
    p.file_name()
        .and_then(|n| n.to_str())
        .expect("pack and prompt file names are UTF-8")
        .to_string()
}
